/**
 * Extract user-visible Chinese strings from the client source fragments.
 *
 * This is an audit tool, not a runtime dependency: it reports the strings that a
 * full i18n pass would have to replace with `t("key")` calls. Output is deterministic
 * (line order), so a diff shows exactly which strings were converted.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dir = join(root, "src", "client");
const names = [
  "00-head.js", "10-locale.js", "20-assets.js", "30-network.js", "40-format.js",
  "50-host.js", "60-search.js", "70-styles.js", "80-core.js", "90-widgets.js",
  "100-sections.js", "110-frame.js", "120-frame-inner.js", "130-apply.js"
];

const rows = [];
for (const name of names) {
  const lines = readFileSync(join(dir, name), "utf8").split("\n");
  lines.forEach((line, i) => {
    // Skip comments and the dictionary fragment itself.
    const trimmed = line.trim();
    if (trimmed.startsWith("//") || trimmed.startsWith("*") || trimmed.startsWith("/*")) return;
    if (name === "10-locale.js") return;
    // Match double-quoted string literals containing at least one Han character.
    const re = /"([^"\\]*(?:\\.[^"\\]*)*)"/g;
    let m;
    while ((m = re.exec(line)) !== null) {
      const value = m[1];
      if (!/[\u4e00-\u9fff]/.test(value)) continue;
      rows.push({ file: name, line: i + 1, text: value });
    }
  });
}

const unique = new Map();
for (const r of rows) {
  if (!unique.has(r.text)) unique.set(r.text, { text: r.text, count: 0, first: r.file + ":" + r.line });
  unique.get(r.text).count += 1;
}
const sorted = [...unique.values()].sort((a, b) => a.first.localeCompare(b.first, "en", { numeric: true }));

const lines = [
  "# Client UI strings (auto-generated)",
  "",
  "Generated by `node tools/i18n-extract.mjs`. Do not edit by hand.",
  "",
  "A full i18n pass replaces each string below with a `t(\"key\")` call. Grouped by first",
  "occurrence in the source fragments; `count` is how many times the exact literal appears.",
  "",
  "| # | count | first occurrence | string |",
  "|---|---|---|---|"
];
sorted.forEach((r, i) => {
  lines.push("| " + (i + 1) + " | " + r.count + " | `" + r.first + "` | " + JSON.stringify(r.text) + " |");
});
lines.push("", "Total literals: " + rows.length + " (" + sorted.length + " unique).");

writeFileSync(join(root, "docs", "i18n-strings.md"), lines.join("\n") + "\n", "utf8");
console.log("literals:", rows.length, "unique:", sorted.length);
